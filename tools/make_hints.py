#!/usr/bin/env python3
"""Turn an interpreter coverage list into a minimal hints file: the fewest extra
entry points that make static discovery cover every executed instruction.
usage: make_hints.py IMAGE COVERAGE OUT --entry ... --code-range LO-HI"""
import argparse, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "recomp"))
from recomp8080 import discover

ap = argparse.ArgumentParser()
ap.add_argument("image"); ap.add_argument("coverage"); ap.add_argument("out")
ap.add_argument("--entry", type=lambda s: int(s, 0), action="append", default=[])
ap.add_argument("--code-range", default="0x0000-0x1fff")
a = ap.parse_args()
mem = bytearray(0x10000)
data = open(a.image, "rb").read()
mem[:len(data)] = data
lo, hi = (int(x, 0) for x in a.code_range.split("-"))
executed = sorted(int(l, 16) for l in open(a.coverage) if l.strip())
entries = list(a.entry)
found, _ = discover(mem, entries, lo, hi)
static_n = len(found)
hints = []
for pc in executed:
    if pc not in found:
        hints.append(pc)
        found, _ = discover(mem, entries + hints, lo, hi)
missing = [pc for pc in executed if pc not in found]
assert not missing, missing
with open(a.out, "w") as f:
    f.write("# Extra entry points for recomp8080.py: code reached only through PCHL\n"
            "# (the object-handler dispatcher at 026E) or as its planted return address.\n"
            "# Generated by tools/make_hints.py from interpreter coverage.\n")
    for h in hints:
        f.write("%04x\n" % h)
print("static discovery: %d insns; executed: %d; hints: %d -> %d insns" % (static_n, len(executed), len(hints), len(found)))
